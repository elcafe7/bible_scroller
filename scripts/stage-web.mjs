#!/usr/bin/env node
// Stage the built dist/ as a public static web app under a URL prefix (default /scroll/ on apocalypse.press).
// Usage: npm run build && node scripts/stage-web.mjs <outDir> [/scroll/]
// Writes <outDir>/index.html, assets/, data/, .htaccess (normal caching; no ?v= query, no demo no-cache).
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const DIST = join(ROOT, "dist");
const out = process.argv[2] && resolve(process.argv[2]);
const base = (process.argv[3] ?? "/scroll/").replace(/^\/?/, "/").replace(/\/?$/, "/");
if (!out) { console.error("usage: node scripts/stage-web.mjs <outDir> [/scroll/]"); process.exit(1); }
if (!existsSync(join(DIST, "index.html")) || !existsSync(join(DIST, "data/geneva/meta.json"))) {
  console.error("stage-web: run npm run build (with full data/) first"); process.exit(1);
}
const html = readFileSync(join(DIST, "index.html"), "utf8");
if (/\?v=/.test(html)) { console.error("stage-web: dist/index.html has a ?v= cache-buster; rebuild"); process.exit(1); }
const inline = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(
  (m) => `'sha256-${createHash("sha256").update(m[1]).digest("base64")}'`,
);

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
writeFileSync(join(out, "index.html"), html);
cpSync(join(DIST, "assets"), join(out, "assets"), { recursive: true });
cpSync(join(DIST, "data"), join(out, "data"), { recursive: true });
if (!existsSync(join(DIST, "LICENSE"))) { console.error("stage-web: dist/LICENSE missing; rebuild"); process.exit(1); }
cpSync(join(DIST, "LICENSE"), join(out, "LICENSE"));

// Offline link from the welcome card + footer: the public GitHub release page (zip is an asset there; not hosted here).
const { version } = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));
const zipUrl = `https://github.com/elcafe7/bible_scroller/releases/tag/v${version}`;
if (html.split(`href="${zipUrl}"`).length - 1 !== 2) {
  console.error(`stage-web: index.html must link ${zipUrl} from the card and the footer`); process.exit(1);
}

const csp = [
  "default-src 'self'",
  `script-src 'self' ${inline.join(" ")} https://static.cloudflareinsights.com`,
  "style-src 'self'",
  "img-src 'self' data:",
  "connect-src 'self' https://cloudflareinsights.com",
  "object-src 'none'", "base-uri 'self'", "frame-ancestors 'none'", "form-action 'self'",
].join("; ");

writeFileSync(join(out, ".htaccess"), `# Scroll (bible_scroller) static app for ${base}. Nothing here executes server-side.
# Generated by scripts/stage-web.mjs. Normal public caching (hashed assets immutable; shell revalidates).
Options -Indexes -MultiViews
DirectoryIndex index.html
DirectorySlash On

AddType application/json .json
AddType text/javascript .js
AddType text/css .css
AddDefaultCharset utf-8
AddCharset utf-8 .json .js .css .html

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/javascript application/javascript application/json
</IfModule>

<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteBase ${base}
  # Single-page app with no routes: real files are served; anything missing is a plain 404 (no shell fallback,
  # so a missing data/*.json shows the app's own "Bible data missing" message instead of HTML-as-JSON).
  RewriteCond %{REQUEST_FILENAME} -f
  RewriteRule ^ - [L]
</IfModule>

<Files "LICENSE">
  ForceType text/plain
</Files>

<IfModule mod_headers.c>
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set X-Content-Type-Options "nosniff"
  Header always set X-Frame-Options "DENY"
  Header always set Permissions-Policy "interest-cohort=(), browsing-topics=()"
  Header always set Content-Security-Policy "${csp}"
  # Vite content-hashed bundles never change: cache for a year.
  <FilesMatch "^(index|style)-[A-Za-z0-9_-]{8}\\.(js|css)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  # Bible/commentary JSON (not hashed; changes only on a data rebuild): one day.
  <FilesMatch "\\.json$">
    Header set Cache-Control "public, max-age=86400"
  </FilesMatch>
  <Files "LICENSE">
    Header set Cache-Control "public, max-age=86400"
  </Files>
  # The HTML shell revalidates so a new build's asset names are picked up.
  <FilesMatch "^index\\.html$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>
`);
console.log(`stage-web: ${out} for ${base} (inline script hashes: ${inline.length}; offline link ${zipUrl})`);
